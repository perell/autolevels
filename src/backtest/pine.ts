/**
 * Generates a TradingView Pine Script (v6) that draws what the engine saw: zones, Monday levels
 * and backtest trades. Paste it into the Pine Editor on a DE30 chart to compare with your own levels.
 */
import type { BacktestResult } from './simulate';

export interface PineOptions {
  maxZones: number;
  maxTrades: number;
  maxWeeks: number;
}

const r = (n: number) => Math.round(n * 100) / 100;
const ms = (s: number) => s * 1000;

export function makePine(res: BacktestResult, opt: PineOptions = { maxZones: 250, maxTrades: 120, maxWeeks: 20 }): string {
  const traded = new Set(res.trades.map((t) => t.zoneId));
  const zones = res.zones.slice(-opt.maxZones);
  const trades = res.trades.slice(-opt.maxTrades);
  const mondays = res.mondays.slice(-opt.maxWeeks);

  const L: string[] = [];
  L.push('//@version=6');
  L.push('// Generated by autolevels backtest: zones, Monday levels and trades as the engine saw them.');
  L.push('indicator("autolevels engine overlay", overlay = true, max_boxes_count = 500, max_lines_count = 500, max_labels_count = 500)');
  L.push('showFilled = input.bool(true, "Show filled / expired zones")');
  L.push('showTrades = input.bool(true, "Show trades")');
  L.push('showMonday = input.bool(true, "Show Monday high / low / mid")');
  L.push('buyCol = color.new(color.teal, 80)');
  L.push('sellCol = color.new(color.red, 80)');
  L.push('deadCol = color.new(color.gray, 88)');
  L.push('');
  L.push('z(int l, int rgt, float top, float bot, bool buy, bool alive, bool traded) =>');
  L.push('    if alive or showFilled');
  L.push('        bg = alive ? (buy ? buyCol : sellCol) : deadCol');
  L.push('        bc = traded ? color.blue : color.new(buy ? color.teal : color.red, alive ? 30 : 75)');
  L.push('        box.new(l, top, rgt, bot, xloc = xloc.bar_time, bgcolor = bg, border_color = bc, border_width = traded ? 2 : 1, extend = alive ? extend.right : extend.none)');
  L.push('');
  L.push('m(int l, float hi, float lo, float mid) =>');
  L.push('    if showMonday');
  L.push('        rgt = l + 5 * 86400000');
  L.push('        line.new(l, hi, rgt, hi, xloc = xloc.bar_time, color = color.orange, width = 2)');
  L.push('        line.new(l, lo, rgt, lo, xloc = xloc.bar_time, color = color.orange, width = 2)');
  L.push('        line.new(l, mid, rgt, mid, xloc = xloc.bar_time, color = color.orange, style = line.style_dashed)');
  L.push('');
  L.push('t(int et, float ep, int xt, float xp, bool buy, string txt) =>');
  L.push('    if showTrades');
  L.push('        label.new(et, ep, buy ? "B" : "S", xloc = xloc.bar_time, style = buy ? label.style_label_up : label.style_label_down, color = buy ? color.teal : color.red, textcolor = color.white, size = size.tiny, tooltip = txt)');
  L.push('        line.new(et, ep, xt, xp, xloc = xloc.bar_time, color = (xp >= ep) == buy ? color.green : color.maroon, width = 2)');
  L.push('');
  L.push('if barstate.islast');
  const end = res.lastEntryBar ?? 0;
  for (const zz of zones) {
    const alive = zz.alive && !zz.traded;
    const right = zz.diedAt ?? zz.expiredAt ?? end;
    L.push(
      `    z(${ms(zz.startTime)}, ${ms(right)}, ${r(zz.origHigh)}, ${r(zz.origLow)}, ${zz.side === 'buy'}, ${alive}, ${traded.has(zz.id)})`,
    );
  }
  for (const mm of mondays) {
    const [y, mo, d] = mm.date.split('-').map(Number);
    L.push(`    m(timestamp("Europe/Berlin", ${y}, ${mo}, ${d}, 0, 0), ${r(mm.high)}, ${r(mm.low)}, ${r(mm.mid)})`);
  }
  for (const tr of trades) {
    const tip = `${tr.side} ${tr.trigger}, score ${tr.score} (${tr.scoreParts.join(' ') || '-'}), ${tr.exitReason} ${r(tr.points)} pts`;
    L.push(`    t(${ms(tr.entryTime)}, ${r(tr.entry)}, ${ms(tr.exitTime)}, ${r(tr.exit)}, ${tr.side === 'buy'}, "${tip}")`);
  }
  return L.join('\n') + '\n';
}
